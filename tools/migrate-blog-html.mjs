#!/usr/bin/env node
/**
 * One-off migration: convert every translated blog `bodyHtml` from
 * MDX-style SOURCE text (import line + Markdown + <FAQ> JSX) into real,
 * styled HTML so the article template's `set:html` renders it properly.
 *
 * Rewrites src/i18n/blog/{es,zh-hant,fr,ar,pt,it,de,ru,ja,ko}.ts in place,
 * preserving the GENERATED header, export name and 2-space indentation.
 * i18n:check stays clean because the manifest hashes the ENGLISH source
 * (`body`), not the translated bodyHtml.
 *
 * Usage: node tools/migrate-blog-html.mjs [--dry-run]
 */

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { renderTranslatedBody } from '../scripts/blog-md-render.mjs';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
// Windows path fix: on win32, URL pathname yields /D:/... which path.resolve
// mis-handles; derive from cwd instead.
const ROOT_DIR = process.cwd();
const DIR = path.join(ROOT_DIR, 'src', 'i18n', 'blog');

const LANGS = ['es', 'zh-hant', 'fr', 'ar', 'pt', 'it', 'de', 'ru', 'ja', 'ko'];
const dryRun = process.argv.includes('--dry-run');

/** Serialize a JS value with 2-space indentation, matching i18n-sync.mjs `ser`. */
function ser(v, indent = 0) {
  const pad = '  '.repeat(indent);
  const padIn = '  '.repeat(indent + 1);
  if (v === undefined || v === null) return 'undefined';
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) {
    if (v.length === 0) return '[]';
    return `[\n${v.map((x) => `${padIn}${ser(x, indent + 1)},`).join('\n')}\n${pad}]`;
  }
  const keys = Object.keys(v);
  if (keys.length === 0) return '{}';
  const body = keys
    .map((k) => `${padIn}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${ser(v[k], indent + 1)},`)
    .join('\n');
  return `{\n${body}\n${pad}}`;
}

/** Load a locale blog table (bundled to CJS via esbuild, like i18n-sync). */
function loadTable(lang) {
  const file = path.join(DIR, `${lang}.ts`);
  const out = require('esbuild').buildSync({
    entryPoints: [file],
    bundle: true,
    format: 'cjs',
    platform: 'node',
    write: false,
    logLevel: 'silent',
  });
  const mod = { exports: {} };
  new Function('module', 'exports', 'require', out.outputFiles[0].text)(mod, mod.exports, require);
  return Object.values(mod.exports)[0];
}

const camel = (locale) => locale.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const GENERATED_HEADER = `// GENERATED FILE — do not edit by hand.
// Regenerated by \`npm run i18n:update\` from the English single source of
// truth. Hand edits to a field are overwritten when the English version of
// that field changes; fields that are absent fall back to English at build
// time (see src/i18n/product-content.ts / blog-content.ts / category-content.ts).
`;

let changed = 0;
let errors = 0;

for (const lang of LANGS) {
  const file = path.join(DIR, `${lang}.ts`);
  if (!fs.existsSync(file)) {
    console.log(`[skip] ${lang}: no file`);
    continue;
  }
  const table = loadTable(lang);
  let modified = false;

  for (const [postId, entry] of Object.entries(table)) {
    if (!entry || typeof entry.bodyHtml !== 'string') continue;
    const before = entry.bodyHtml;
    // Only convert if it still looks like Markdown source (has import/##/table/FAQ JSX).
    const looksSource =
      /^\s*import\s+FAQ/i.test(before) ||
      /^#{1,3}\s/m.test(before) ||
      /<FAQ[\s>]/.test(before);
    if (!looksSource) continue;

    const after = await renderTranslatedBody(before);
    if (after === before) continue;
    entry.bodyHtml = after;
    modified = true;
    changed++;
    console.log(`[ok] ${lang}/${postId}: converted (${before.length} -> ${after.length} chars)`);
  }

  if (!modified) {
    console.log(`[  ] ${lang}: nothing to convert`);
    continue;
  }
  if (dryRun) {
    console.log(`[dry-run] ${lang}: would rewrite (not written)`);
    continue;
  }

  const src = `${GENERATED_HEADER}
import type { BlogTable } from '../blog-content';

export const ${camel(lang)}Blog: BlogTable = ${ser(table)};
`;
  fs.writeFileSync(file, src, 'utf8');
  console.log(`[wrote] ${lang}`);
}

console.log(`\nDone: ${changed} body(ies) converted, ${errors} error(s).${dryRun ? ' (dry-run)' : ''}`);
